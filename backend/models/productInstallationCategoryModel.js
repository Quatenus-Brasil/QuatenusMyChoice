import mongoose from "mongoose";
import { Schema } from "mongoose";

const productInstallationCategorySchema = new Schema(
  {
    name: {
      type: String,
      required: true,
    },
    code: {
      type: String,
      required: true,
      unique: true,
    },
    price: {
      type: Number,
      required: true,
    },
    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    updatedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
  },
  { timestamps: true }
);

const ProductInstallationCategory = mongoose.model("ProductInstallationCategory", productInstallationCategorySchema);

export default ProductInstallationCategory;
